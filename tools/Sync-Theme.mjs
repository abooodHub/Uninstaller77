import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const css = readFileSync(new URL('app/WinUninstaller/WebUI/src/theme.css', root), 'utf8')
const colors = Object.fromEntries([...css.matchAll(/^\s*--([\w-]+):\s*#([\da-f]{6});/gim)]
  .map(([, name, rgb]) => [name, rgb.toUpperCase()]))
const roles = {
  Canvas: 'bg-app',
  Chrome: 'bg-sidebar',
  Surface: 'surface-1',
  Track: 'surface-3',
  Text: 'text-1',
  Muted: 'text-2',
  Accent: 'accent',
  AccentHover: 'accent-hover',
}
const palette = Object.entries(roles).map(([name, role]) => {
  const rgb = colors[role]
  if (!rgb) throw new Error('Missing six-digit hex theme color: ' + role)
  const [r, g, b] = rgb.match(/../g)
  return { name, rgb, bgr: b + g + r }
})

const source = new URL('app/WinUninstaller/Views/ProductTheme.Colors.cs', root)
const inno = new URL('installer/Theme.iss', root)
const header = '// Generated by tools/Sync-Theme.mjs from WebUI/src/theme.css.\n'
const nativeRoles = new Set(['Canvas', 'Chrome', 'Surface', 'Text', 'Muted'])
const csColors = palette.filter(({ name }) => nativeRoles.has(name))
  .map(({ name, rgb }) => '    private const int ' + name + 'Rgb = 0x' + rgb + ';')
const setupColors = palette.map(({ name, bgr }) => '#define Theme' + name + ' "$00' + bgr + '"')
const outputs = new Map([
  [source, header + 'namespace WinUninstaller.Views;\n\npublic static partial class ProductTheme\n{\n' + csColors.join('\n') + '\n}\n'],
  [inno, header + setupColors.join('\n') + '\n'],
])

for (const [file, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== content)
      throw new Error('Theme colors are out of date. Run node tools/Sync-Theme.mjs.')
  } else {
    writeFileSync(file, content)
  }
}
console.log('Theme colors match WebUI, WPF and Inno Setup.')
