// Screenshots remain ordinary image links when JavaScript is unavailable.
const galleryCards = [...document.querySelectorAll('.gallery-card')];
const galleryFilters = [...document.querySelectorAll('[data-gallery-filter]')];
const viewer = document.getElementById('image-viewer');
const viewerImage = document.getElementById('viewer-image');
let activeImage = null;
let returnFocus = null;

function visibleImages() {
  return galleryCards.filter(card => !card.hidden).map(card => card.querySelector('.gallery-open'));
}
function renderImage(link) {
  activeImage = link;
  const card = link.closest('.gallery-card');
  const image = link.querySelector('img');
  viewerImage.src = link.href;
  document.getElementById('viewer-original').href = link.href;
  viewerImage.alt = image.alt;
  document.getElementById('viewer-title').textContent = card.querySelector('h3').textContent;
  document.getElementById('viewer-note').textContent = card.querySelector('.gallery-copy p').textContent;
  const visible = visibleImages();
  document.getElementById('viewer-position').textContent = `${visible.indexOf(link) + 1} / ${visible.length}`;
}
function navigateImage(delta) {
  const visible = visibleImages();
  const index = visible.indexOf(activeImage);
  if (!visible.length) return;
  renderImage(visible[(index + delta + visible.length) % visible.length]);
}
function closeViewer() { viewer.close(); }

for (const filter of galleryFilters) {
  filter.addEventListener('click', () => {
    const category = filter.dataset.galleryFilter;
    for (const card of galleryCards) card.hidden = category !== 'all' && card.dataset.category !== category;
    for (const button of galleryFilters) button.setAttribute('aria-pressed', String(button === filter));
    document.getElementById('gallery-count').textContent = `${visibleImages().length} / ${galleryCards.length}`;
  });
}
for (const link of document.querySelectorAll('.gallery-open')) {
  link.addEventListener('click', event => {
    if (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey || event.button !== 0) return;
    if (typeof viewer.showModal !== 'function') return;
    event.preventDefault();
    returnFocus = link;
    renderImage(link);
    viewer.showModal();
    document.body.classList.add('viewer-open');
  });
}
document.getElementById('viewer-close').addEventListener('click', closeViewer);
document.getElementById('viewer-previous').addEventListener('click', () => navigateImage(-1));
document.getElementById('viewer-next').addEventListener('click', () => navigateImage(1));
viewer.addEventListener('keydown', event => {
  if (event.key !== 'ArrowRight' && event.key !== 'ArrowLeft') return;
  event.preventDefault();
  const rtl = document.documentElement.dir === 'rtl';
  navigateImage((event.key === 'ArrowRight' ? 1 : -1) * (rtl ? -1 : 1));
});
viewer.addEventListener('click', event => {
  if (event.target !== viewer) return;
  const bounds = viewer.getBoundingClientRect();
  if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) closeViewer();
});
viewer.addEventListener('close', () => {
  document.body.classList.remove('viewer-open');
  if (returnFocus?.isConnected) returnFocus.focus({preventScroll:true});
});
document.addEventListener('u77-language-change', () => { if (viewer.open && activeImage) renderImage(activeImage); });

document.getElementById('copy-page-link').addEventListener('click', async () => {
  const ar = document.documentElement.lang === 'ar';
  const status = document.getElementById('share-status');
  const copyButton = document.getElementById('copy-page-link');
  let deadline;
  copyButton.disabled = true;
  try {
    await Promise.race([
      navigator.clipboard.writeText('https://abooodhub.github.io/Uninstaller77/'),
      new Promise((_, reject) => { deadline = setTimeout(() => reject(new Error('Clipboard unavailable')), 2000); })
    ]);
    status.textContent = ar ? arabic.shareCopied : 'Product page link copied.';
  } catch {
    status.textContent = ar ? arabic.shareUnavailable : 'Select the displayed link and copy it.';
    const input = document.getElementById('page-link');
    input.focus();
    input.select();
  } finally {
    clearTimeout(deadline);
    copyButton.disabled = false;
  }
});

