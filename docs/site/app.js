const galleryCards = [...document.querySelectorAll('.gallery-card')];
const galleryFilters = [...document.querySelectorAll('[data-gallery-filter]')];
const viewer = document.getElementById('image-viewer');
const viewerImage = document.getElementById('viewer-image');
let activeImage = null;
let returnFocus = null;

function visibleImages() {
  return galleryCards.filter(card => !card.hidden).map(card => card.querySelector('.gallery-open'));
}
function renderImage(link) {
  activeImage = link;
  const card = link.closest('.gallery-card');
  const image = link.querySelector('img');
  viewerImage.src = link.href;
  document.getElementById('viewer-original').href = link.href;
  viewerImage.alt = image.alt;
  document.getElementById('viewer-title').textContent = card.querySelector('h3').textContent;
  document.getElementById('viewer-label').textContent = [...card.querySelectorAll('.gallery-label > span')].map(node => node.textContent).join(' · ');
  document.getElementById('viewer-note').textContent = card.querySelector('.capture-note').textContent;
  const visible = visibleImages();
  document.getElementById('viewer-position').textContent = `${visible.indexOf(link) + 1} / ${visible.length}`;
}
function navigateImage(delta) {
  const visible = visibleImages();
  const index = visible.indexOf(activeImage);
  if (!visible.length) return;
  renderImage(visible[(index + delta + visible.length) % visible.length]);
}
function closeViewer() { viewer.close(); }

for (const filter of galleryFilters) {
  filter.addEventListener('click', () => {
    const category = filter.dataset.galleryFilter;
    for (const card of galleryCards) card.hidden = category !== 'all' && card.dataset.category !== category;
    for (const button of galleryFilters) button.setAttribute('aria-pressed', String(button === filter));
    document.getElementById('gallery-count').textContent = `${visibleImages().length} / ${galleryCards.length}`;
  });
}
for (const link of document.querySelectorAll('.gallery-open')) {
  link.addEventListener('click', event => {
    if (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey || event.button !== 0) return;
    if (typeof viewer.showModal !== 'function') return;
    event.preventDefault();
    returnFocus = link;
    renderImage(link);
    viewer.showModal();
    document.body.classList.add('viewer-open');
  });
}
